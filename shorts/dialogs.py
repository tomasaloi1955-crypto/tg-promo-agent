def episode(n: int, d: dict) -> dict:
    rng = random.Random(n)
    order = []
    for ln in d["lines"]:
        if ln[0] not in order:
            order.append(ln[0])
    pos = {2: [0.27, 0.73], 3: [0.18, 0.5, 0.82]}[len(order)] if len(order) > 1 else [0.5]
    places = dict(zip(order, pos))
    enter = order[-1] if len(order) == 2 and rng.random() < 0.4 else None
    cast = {k: v for k, v in places.items() if k != enter}

    beats = [
        {"scene": d["scene"], "cast": cast},
        {"hook": f"*{d['topic']}* — по-арабски", "speak": f"{d['topic']} — по-арабски"},
    ]
    if enter:
        beats.append({"enter": enter, "to": places[enter]})
    for ln in d["lines"]:
        who, ar, tr, ru = ln[:4]
        b = {"say": who, "ar": ar, "tr": tr, "ru": ru}
        if len(ln) > 4:
            b["mood"] = ln[4]
        else:
            b["mood"] = "neutral"
        beats.append(b)
    car, ctr, cru = d["card"]
    beats.append({"card": {"label": "ЗАПОМНИ", "ar": car, "tr": ctr, "ru": cru}})
    return {
        "title": f"Урок {n}: *{d['topic']}*",
        "channel": "MY ARABIC",
        "footer": "Учим арабский по мультикам",
        "narrator": {"ar": "ar-SA-HamedNeural", "ru": "ru-RU-SvetlanaNeural"},
        "characters": {k: CHARACTERS[k] for k in order},
        "beats": beats,
        "outro": "Повтори вслух — и *подпишись*!",
        "outro_speak": "Повтори вслух и подпишись!",
    }


def main():
    assert len(DIALOGS) == 100, len(DIALOGS)
    out = HERE / "episodes"
    out.mkdir(exist_ok=True)
    for old in out.glob("dialog_*.json"):
        old.unlink()
    md = ["# 100 диалогов для Shorts «My Arabic»", "",
          "Литературный арабский (фусха). Файлы сценариев: `shorts/episodes/dialog_NNN.json` "
          "(генерируются из `shorts/dialogs.py`).", ""]
    for n, d in enumerate(DIALOGS, 1):
        (out / f"dialog_{n:03d}.json").write_text(json.dumps(episode(n, d), ensure_ascii=False, indent=1), encoding="utf-8")
        md.append(f"## {n}. {d['topic']}")
        md.append("")
        for ln in d["lines"]:
            who = CHARACTERS[ln[0]]["name"]
            md.append(f"- **{who}:** {ln[1].replace('*', '')} — _{ln[2].replace('*', '')}_ — {ln[3].replace('*', '')}")
        car, ctr, cru = d["card"]
        md.append(f"- 📌 **Запомни:** {car} — _{ctr}_ — {cru}")
        md.append("")
    (HERE / "DIALOGS.md").write_text("\n".join(md), encoding="utf-8")
    print(f"✓ {len(DIALOGS)} эпизодов → {out}, список → {HERE / 'DIALOGS.md'}")


if __name__ == "__main__":
    main()
